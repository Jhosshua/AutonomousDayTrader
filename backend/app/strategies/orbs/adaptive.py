def card_risk_pct(card):
    """The card's stop distance as a percentage of entry price."""
    e, st = _num(card.get("entry")), _num(card.get("stop"))
    if e in (None, 0) or st is None: return None
    return abs(e - st) / e * 100.0

def card_drift_ratio(card):
    """Drift as a fraction of the card's own stop distance."""
    r = card_risk_pct(card)
    d = _num(card.get("drift_pct"))
    if r in (None, 0) or d is None: return None
    return d / r

def evaluate_microstructure(card):
    """Validate required card metrics and calculate a heuristic participation proxy."""
    if not core._valid_card(card):
        return False, "invalid card prices or direction"
    spread = _num(card.get("spread_bps"))
    if spread is None or spread < 0:
        return False, "spread unavailable or invalid"
    if spread > ADAPTIVE_CONFIG["MAX_SPREAD_BPS"]:
        return False, f"spread {spread:.1f} bps > {ADAPTIVE_CONFIG['MAX_SPREAD_BPS']} bps limit"

    rd = card_risk_pct(card)
    if rd is None or rd > ADAPTIVE_CONFIG["MAX_STOP_PCT"]:
        return False, f"stop distance {rd if rd is not None else 'unknown'}% > {ADAPTIVE_CONFIG['MAX_STOP_PCT']}% cap"
    if rd < ADAPTIVE_CONFIG["MIN_STOP_PCT"]:
        return False, f"stop distance {rd:.2f}% < {ADAPTIVE_CONFIG['MIN_STOP_PCT']}% minimum"

    dr = card_drift_ratio(card)
    if dr is None:
        return False, "drift unavailable or invalid"
    if dr > ADAPTIVE_CONFIG["MAX_DRIFT_R"]:
        return False, f"drift spent {dr*100:.0f}% of stop distance (> {ADAPTIVE_CONFIG['MAX_DRIFT_R']*100:.0f}% cap)"

    rvol = _num(card.get("rvol"), 0.0)
    if rvol < ADAPTIVE_CONFIG["MIN_RVOL"]:
        return False, f"RVOL {rvol:.1f}x < {ADAPTIVE_CONFIG['MIN_RVOL']}x threshold"

    atr = _num(card.get("atr_pct"), 0.0)
    if atr < ADAPTIVE_CONFIG["MIN_ATR_PCT"]:
        return False, f"ATR {atr:.1f}% < {ADAPTIVE_CONFIG['MIN_ATR_PCT']}% room threshold"

    raw_sofi = card.get("sofi") if "sofi" in card else card.get("sofi_z")
    sofi_z = _num(raw_sofi)
    if sofi_z is None:
        return False, "SOFI participation z-score unavailable or invalid"
    sofi_z = abs(sofi_z)
    z_tps = round(0.6 * (rvol - 2.0) + 0.4 * (sofi_z - 2.0) + 2.0, 2)

    return True, {
        "z_tps": z_tps,
        "spread_bps": spread,
        "rd_pct": round(rd, 2),
        "drift_r": round(dr if dr is not None else 0.0, 3),
        "rvol": rvol,
        "atr_pct": atr
    }

