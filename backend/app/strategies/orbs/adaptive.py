def select_adaptive(cards, day=None, freeze_time="09:38", earnings=None,
                    spy_slope=None, qqq_slope=None, earn_reprice_gap=None, deals=None):
    """Executes the complete adaptive decision logic:
    1. Regime Check (sitting 100% in cash if hostile).
    2. Microstructure & Tape Filtration.
    3. Benzinga NLP Catalyst classification.
    4. Bayesian Utility Scoring & Ranking.
    5. Sector Diversification for Trade 2.
    Returns: (picks, audit_rows, regime_info)
    """
    day = day or core.today()
    earnings_injected = earnings is not None
    regime = evaluate_market_regime(
        day, freeze_time, cards=cards, spy_slope=spy_slope, qqq_slope=qqq_slope)
    audit_rows = []
    earn_reprice_gap = _num(
        config.EARN_REPRICE_GAP if earn_reprice_gap is None else earn_reprice_gap)
    if earn_reprice_gap is None or earn_reprice_gap < 0:
        regime["classification"] = "UNKNOWN"
        regime["action"] = "SIT_OUT_CASH"
        regime["reasons"].append("Earnings reprice threshold is unavailable or invalid")

    # If Market Regime forces 100% Cash Sit-Out:
    if regime["action"] == "SIT_OUT_CASH":
        audit_rows.append({
            "symbol": "*",
            "tier": "regime",
            "survives": False,
            "case_against_strength": "specific",
            "why": f"Market Regime Sit-Out: {'; '.join(regime['reasons'])}"
        })
        return [], audit_rows, regime

    # Fetch earnings headlines if not provided. A complete empty result is valid;
    # an unavailable/partial producer response is an explicit cash pass because
    # dilution cannot be ruled out safely.
    deals_injected = deals is not None
    if earnings is None:
        try:
            freeze_dt = _freeze_dt(day, freeze_time)
            earnings = fetch_earnings_headlines([c["symbol"] for c in cards], freeze_dt)
        except Exception as exc:
            regime["classification"] = "UNKNOWN"
            regime["action"] = "SIT_OUT_CASH"
            reason = "Company news unavailable or incomplete; dilution cannot be verified"
            if reason not in regime["reasons"]:
                regime["reasons"].append(reason)
            # The ledger keeps the exact failure for the operator; before 2026-10-02 the
            # cause was dropped here and a sat-out day could not be explained afterwards.
            try:
                core._ledger({"kind": "news_unavailable", "day": day,
                              "why": str(exc) or type(exc).__name__,
                              "detail": getattr(exc, "detail", None)})
            except Exception:
                pass
            _record_health("news", "Company news", "error",
                           "Company news could not be verified completely; adaptive entries are paused.",
                           "Check the market data connection and retry the decision.")
            audit_rows.append({"symbol": "*", "tier": "news", "survives": False,
                               "case_against_strength": "specific", "why": reason})
            return [], audit_rows, regime

    # Deal rule: its own fetch and budget AFTER the earnings fetch; it never sits the day out.
    if not config.DEAL_RULE:
        deals = {}
    elif deals_injected:
        deals = dict(deals)
    elif earnings_injected:
        deals = {}
    else:
        try:
            shorts = [c.get("symbol") for c in cards if c.get("direction") == "short"]
            deals, _complete = fetch_deal_headlines(shorts, _freeze_dt(day, freeze_time))
        except Exception:
            deals, _complete = {}, False
            _record_health("deal_news", "Deal news", "warning",
                           "Deal news could not be read completely; shorts not already blocked trade as normal.",
                           "Check the relay news proxy.")
        regime["deal_news_complete"] = bool(_complete)
        _DEAL_BLOCKED.setdefault(str(day), {}).update(deals)
        for sym, row in _sticky_deal_blocks(day).items():
            deals.setdefault(sym, row)

    candidates = []

    # Flow rule 3 (macro veto): one relay call for the whole board. A pick against SPY or its sector ETF
    # is dropped here, before ranking, so its slot can go to another name; core.execute() re-checks.
    macro_why = {}
    if config.MACRO_RULE and cards:
        from . import flow
        try:
            macro_now = core.now_et() if str(day) == core.today() else _freeze_dt(day, freeze_time)
        except Exception:
            macro_now = core.now_et()
        macro_why = flow.macro_refusals(
            [{"symbol": c.get("symbol", ""), "direction": c.get("direction")} for c in cards], now=macro_now)

    # JhoshuaStraddle: an account that cannot short skips shorts HERE, after the regime check has
    # already read the whole board's short share, so the best long can still be pick 1.
    skip_shorts = core.long_only()
    for c in cards:
        sym = c.get("symbol", "")
        if skip_shorts and c.get("direction") == "short":
            audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                "case_against_strength": "specific", "why": "Long-only account (cannot short)"})
            continue
        if config.CANDLE_RULE:
            why = signals.candle_refusal(c)
            if why:
                audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                    "case_against_strength": "specific", "why": "Candle rule: " + why})
                continue
        flow_why = __import__(__package__ + ".flow", fromlist=["flow_refusal"]).flow_refusal(c)
        if flow_why:
            audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                "case_against_strength": "specific", "why": "Flow rule: " + flow_why})
            continue
        if config.MACRO_RULE and macro_why.get(sym, "no macro verdict"):
            audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                "case_against_strength": "specific", "why": "Macro veto: " + macro_why.get(sym, "no macro verdict")})
            continue
        deal = deals.get(str(sym).upper()) if c.get("direction") == "short" else None
        if deal:
            audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                "case_against_strength": "specific",
                "why": f"Deal rule: company announced a new deal {str(deal.get('ts', ''))[-5:]} "
                       f"'{str(deal.get('headline', ''))[:80]}'",
                "deal": {"ts": deal.get("ts", ""), "headline": str(deal.get("headline", ""))[:140]}})
            continue
        e_data = earnings.get(sym)
        if e_data:
            age = _num(e_data.get("hours_ago"))
            if age is None or not 0 <= age <= 48:
                e_data = None
        if e_data and e_data.get("catalyst", {}).get("tier") == "T3" and c.get("direction") == "long":
            audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                "case_against_strength": "specific", "why": "Dilutive offering vetoes a long entry"})
            continue

        # Microstructure validation
        micro_ok, micro_info = evaluate_microstructure(c)
        if not micro_ok:
            audit_rows.append({
                "symbol": sym,
                "tier": "structure",
                "survives": False,
                "case_against_strength": "specific",
                "why": micro_info
            })
            continue

        cat_tier = "structure"
        cat_summary = ""
        is_earnings = False
        reprice = False

        if e_data:
            cat_grade = e_data.get("result")
            is_long = c.get("direction") == "long"
            if (cat_grade == "beat" and is_long) or (cat_grade == "miss" and not is_long):
                cat_tier = "earnings"
                is_earnings = True
                cat_summary = f"Reported {e_data['hours_ago']}h ago, {cat_grade} agrees with {c['direction']}"
            elif (cat_grade == "beat" and not is_long):
                gap = _num(c.get("gap_pct"), 0.0)
                if gap >= earn_reprice_gap:
                    cat_tier = "earnings"
                    is_earnings = True
                    reprice = True
                    cat_summary = f"Reported {e_data['hours_ago']}h ago, beat but fading gap +{gap:.1f}%"

        # Enforce contract requirement: earnings pick must have drift > -0.5%
        drift = _num(c.get("drift_pct"))
        if is_earnings and drift is not None and drift <= -0.5:
            audit_rows.append({
                "symbol": sym,
                "tier": "earnings",
                "survives": False,
                "case_against_strength": "specific",
                "why": f"drift {drift:.2f}% <= -0.5% floor (contract required)"
            })
            continue

        if not is_earnings:
            # Check if there is a confirmed non-earnings catalyst (T2 contract/FDA, T4 guidance)
            has_valid_cat = False
            if e_data:
                cat_obj = e_data.get("catalyst", {})
                c_grade = cat_obj.get("grade")
                is_l = c.get("direction") == "long"
                if (c_grade == "positive" and is_l) or (c_grade == "raised" and is_l) or (c_grade == "lowered" and not is_l):
                    has_valid_cat = True
                    cat_summary = f"Catalyst [{e_data['tier']}]: {e_data.get('headline', '')[:80]} | RVOL {micro_info['rvol']:.1f}x"

            if not has_valid_cat:
                if micro_info["drift_r"] < 0:
                    audit_rows.append({"symbol": sym, "tier": "structure", "survives": False,
                        "case_against_strength": "specific", "why": "Failed gap no longer holds its trigger"})
                    continue
                gap = _num(c.get("gap_pct"), 0.0)
                against = -gap * (1 if c.get("direction") == "long" else -1)
                if against < ADAPTIVE_CONFIG["MIN_GAP_REAL"]:
                    audit_rows.append({
                        "symbol": sym,
                        "tier": "structure",
                        "survives": False,
                        "case_against_strength": "specific",
                        "why": f"gap {gap:+.1f}% is not a real failed gap"
                    })
                    continue
                if sym in MEGA:
                    audit_rows.append({
                        "symbol": sym,
                        "tier": "structure",
                        "survives": False,
                        "case_against_strength": "specific",
                        "why": "mega-cap trillion-dollar name barred from failed gap"
                    })
                    continue
                cat_summary = f"Failed gap {gap:+.1f}%, RVOL {micro_info['rvol']:.1f}x, ATR {micro_info['atr_pct']:.1f}%, drift {micro_info['drift_r']*100:.0f}%"

        cat_for_utility = dict(e_data) if e_data else {}
        if reprice:
            cat_for_utility["reprice"] = True
        utility_metrics = compute_bayesian_utility(c, micro_info, cat_for_utility, regime)

        candidates.append({
            "card": c,
            "symbol": sym,
            "direction": c.get("direction"),
            "tier": cat_tier,
            "sector": SECTOR_MAP.get(sym, "OTHER"),
            "reason": cat_summary,
            "reprice": reprice,
            "hours_ago": e_data.get("hours_ago") if e_data else None,
            "earnings_found": is_earnings,
            "direction_aligned": is_earnings and not reprice,
            "micro": micro_info,
            "utility": utility_metrics
        })

    candidates.sort(key=lambda x: -x["utility"]["utility"])

    selected_picks = []
    first_hurdle = ADAPTIVE_CONFIG["CASH_HURDLE_EV"]
    candidates = sorted(candidates, key=lambda x: -x["utility"]["utility"])
    eligible = [c for c in candidates if c["utility"]["ev_dollars"] >= first_hurdle
                and c["utility"]["p_win"] >= ADAPTIVE_CONFIG["MIN_WIN_PROB"] and c["utility"]["utility"] > 0]
    # ADT edit: exclude_symbols leave the pick pool here, after the board and the regime were judged, so the
    # next eligible candidate is promoted to pick 1 / pick 2. An empty set is the exact ORBStraddle behaviour.
    excluded_syms = {str(s).upper() for s in (getattr(config, "EXCLUDE_SYMBOLS", ()) or ())}
    if excluded_syms:
        eligible = [c for c in eligible if c["symbol"] not in excluded_syms]
    if (eligible and ADAPTIVE_CONFIG["MAX_DAILY_PICKS"] >= 1 and
        eligible[0]["utility"]["ev_dollars"] >= first_hurdle):
        pick1 = eligible[0]
        selected_picks.append(pick1)

        if (len(eligible) > 1 and
            ADAPTIVE_CONFIG["MAX_DAILY_PICKS"] >= 2):

            p1_sector = pick1["sector"]
            for cand in eligible[1:]:
                # Sector diversification: reject same sector, and reject if both are unclassified "OTHER"
                if cand["sector"] != p1_sector and "OTHER" not in (cand["sector"], p1_sector):
                    if (cand["utility"]["ev_dollars"] >= ADAPTIVE_CONFIG["SECOND_PICK_HURDLE_EV"] and
                        cand["utility"]["utility"] > 0):
                        selected_picks.append(cand)
                        break

    chosen_syms = {p["symbol"] for p in selected_picks}
    final_picks = []

    for cand in candidates:
        sym = cand["symbol"]
        is_chosen = sym in chosen_syms

        row = {
            "symbol": sym,
            "tier": cand["tier"],
            "survives": is_chosen,
            "case_against_strength": "weak" if is_chosen else "specific",
            "why": cand["reason"] if is_chosen else (cand["reason"] + " | Not selected: excluded_symbol" if sym in excluded_syms else cand["reason"] + " | Not selected: EV/probability/utility hurdle, rank, pick cap, or sector constraint"),
            "utility": cand["utility"]["utility"],
            "ev_dollars": cand["utility"]["ev_dollars"],
            "win_prob": cand["utility"]["p_win"],
            "sector": cand["sector"]
        }

        if cand["tier"] == "earnings":
            row["earnings_found"] = cand["earnings_found"]
            row["direction_aligned"] = cand["direction_aligned"]
            row["hours_ago"] = cand["hours_ago"]
            if cand["reprice"]:
                row["reprice"] = True

        audit_rows.append(row)

        if is_chosen:
            p_dict = {
                "symbol": sym,
                "direction": cand["direction"],
                "tier": cand["tier"],
                "catalyst_summary": (
                    f"{cand['reason']} | EV: +${cand['utility']['ev_dollars']:.0f} "
                    f"({cand['utility']['win_prob']*100:.0f}% model estimate; uncalibrated, per $1k risk) | Sector: {cand['sector']}"
                )
            }
            if cand.get("reprice"):
                p_dict["reprice"] = True
            final_picks.append(p_dict)

    return final_picks, audit_rows, regime

