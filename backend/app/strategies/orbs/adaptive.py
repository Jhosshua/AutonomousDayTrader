def compute_bayesian_utility(card, micro_data, catalyst_data, regime_data):
    """Computes:
    1. Uncalibrated logistic estimate of hitting target (+0.75R).
    2. Expected Value in R and net dollars ($1,000 risk per trade).
    3. Risk-adjusted utility U penalizing parameter uncertainty and tail risk.
    """
    intercept = 0.15
    cat_score = catalyst_data.get("catalyst", {}).get("score", 0.0) if catalyst_data else 0.0
    z_tps = micro_data.get("z_tps", 2.0)
    rvol = micro_data.get("rvol", 2.5)
    drift_r = micro_data.get("drift_r", 0.0)

    spy_slope = regime_data.get("spy_slope", 0.0)
    is_long = card.get("direction") == "long"
    slope_align = 0.0 if spy_slope == 0 else (0.3 if ((spy_slope > 0) == is_long) else -0.4)

    # Align catalyst score with trade direction:
    # A negative catalyst (earnings miss -2.0) is positively aligned (+2.0) for a short trade!
    if catalyst_data and catalyst_data.get("reprice"):
        aligned_cat = abs(cat_score) * 0.5
    else:
        aligned_cat = cat_score if is_long else -cat_score

    mu_score = (
        intercept +
        0.35 * aligned_cat +
        0.25 * (z_tps - 2.0) +
        0.15 * (rvol - 2.5) -
        0.50 * max(0.0, drift_r) +
        0.20 * slope_align
    )

    sigma_sq = 0.18 + (0.10 if aligned_cat == 0.0 else 0.02) + 0.04

    moderated_z = mu_score / math.sqrt(1.0 + (math.pi / 8.0) * sigma_sq)
    p_win = 1.0 / (1.0 + math.exp(-moderated_z))
    p_win = max(0.40, min(0.85, p_win))

    # Normalization of the assumed payoff matrix (PLAN.md Section 4.3):
    # At p_win = 0.50: clawback=0.12, flat=0.08, loss=0.30
    p_rem = max(0.0, 1.0 - p_win)
    p_claw = 0.24 * p_rem
    p_flat = 0.16 * p_rem
    p_loss = 0.60 * p_rem

    p_ff = 0.85 * p_loss
    p_stop = 0.15 * p_loss

    ev_r = (
        0.75 * p_win +
        0.25 * p_claw +
        0.00 * p_flat -
        0.40 * p_ff -
        1.00 * p_stop -
        0.03
    )

    ev_dollars = round(ev_r * 1000.0, 2)
    std_err = math.sqrt(sigma_sq)
    utility = ev_r - ADAPTIVE_CONFIG["LAMBDA_UNCERTAINTY"] * std_err - ADAPTIVE_CONFIG["LAMBDA_TAIL"] * p_stop

    return {
        "p_win": round(p_win, 3),
        "win_prob": round(p_win, 3),
        "ev_r": round(ev_r, 4),
        "ev_dollars": ev_dollars,
        "utility": round(utility, 4),
        "std_err": round(std_err, 3),
        "p_stop": round(p_stop, 3)
    }

