def reply_text(cards, day=None, when=None, earnings=None,
               spy_slope=None, qqq_slope=None, earn_reprice_gap=None):
    """Formats the adaptive decision into the exact JSON contract expected by core.validate."""
    day = day or core.today()
    when = when or config.FREEZE_ET

    picks, audit_rows, regime = select_adaptive(
        cards, day=day, freeze_time=when, earnings=earnings,
        spy_slope=spy_slope, qqq_slope=qqq_slope,
        earn_reprice_gap=earn_reprice_gap)

    is_pass = len(picks) == 0
    note = None
    if is_pass:
        note = f"Adaptive Engine PASSED ({regime['classification']}: {'; '.join(regime['reasons']) if regime['reasons'] else 'no candidate cleared EV hurdle'})"

    reply_obj = {
        "date": day,
        "pass": is_pass,
        "picks": picks,
        "audit": audit_rows,
        "regime": regime,
        "estimate_basis": "Uncalibrated heuristic; EV per $1,000 reference risk",
        "engine": ADAPTIVE_VERSION
    }

    return json.dumps(reply_obj, indent=2), note
