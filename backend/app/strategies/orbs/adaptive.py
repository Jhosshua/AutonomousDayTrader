def _freeze_dt(day, when):
    return datetime.fromisoformat(f"{day}T{when}").replace(tzinfo=ET)


def _vwap_slope(bars, start_dt, end_dt):
    """Return a slope only when every expected one-minute bar is present."""
    expected = []
    cursor = start_dt.replace(second=0, microsecond=0)
    while cursor < end_dt:
        expected.append(cursor)
        cursor += timedelta(minutes=1)
    if len(expected) < 2:
        return None
    points = {}
    for bar in bars:
        try:
            raw_ts = str(bar["t"])
            ts = datetime.fromisoformat(raw_ts.replace("Z", "+00:00"))
            if ts.tzinfo is None or ts.utcoffset() is None or ts.second != 0 or ts.microsecond != 0:
                continue
            ts = ts.astimezone(ET)
            price, volume = _num(bar.get("vw")), _num(bar.get("v"))
            if ts not in expected:
                continue
            if price is not None and volume is not None and price > 0 and volume > 0:
                if ts in points and points[ts] != (price, volume): return None
                points[ts] = (price, volume)
        except (KeyError, TypeError, ValueError, AttributeError):
            continue
    if any(ts not in points for ts in expected):
        return None
    times = expected
    total_pv = total_vol = 0.0
    for ts in times:
        price, volume = points[ts]
        total_pv += price * volume
        total_vol += volume
    first = points[times[0]][0]
    minutes = (times[-1] - times[0]).total_seconds() / 60
    return round((total_pv / total_vol - first) / first * 1e4 / minutes, 2)


def evaluate_market_regime(day, freeze_time="09:38", cards=None,
                           spy_slope=None, qqq_slope=None):
    """Verify complete opening index data and a balanced directional board.

    Explicit SPY and QQQ slopes are deterministic research and test injections.
    Production obtains both values from complete one-minute bars.
    Board direction balance is not market-wide advance and decline breadth.
    """
    freeze_dt = _freeze_dt(day, freeze_time)
    regime = {"day": day, "asof": freeze_dt.isoformat(), "classification": "UNKNOWN",
              "action": "SIT_OUT_CASH", "spy_slope": None, "qqq_slope": None,
              "breadth_ratio": None, "short_frac": None, "reasons": []}
    if spy_slope is not None or qqq_slope is not None:
        regime["spy_slope"] = _num(spy_slope)
        regime["qqq_slope"] = _num(qqq_slope)
    else:
        _record_health("indices", "SPY / QQQ", "waiting", "Checking continuous opening minute bars.")
        try:
            open_dt = freeze_dt.replace(hour=9, minute=30, second=0)
            query = urllib.parse.urlencode({"symbols": "SPY,QQQ", "timeframe": "1Min",
                "start": open_dt.astimezone(timezone.utc).isoformat(),
                "end": freeze_dt.astimezone(timezone.utc).isoformat(), "feed": "sip", "limit": 1000})
            req = urllib.request.Request(config.INDEX_BARS_URL + "?" + query,
                                         headers=dict(config.RELAY_HEADERS))
            payload = _relay_page(req, _t.monotonic() + 9.0, per_try=3.0, what="index bars")
            if not isinstance(payload, dict) or not isinstance(payload.get("bars"), dict):
                raise ValueError("malformed index response")
            bars = payload["bars"]
            for sym, key in (("SPY", "spy_slope"), ("QQQ", "qqq_slope")):
                regime[key] = _vwap_slope(bars.get(sym) or [], open_dt, freeze_dt)
            if regime["spy_slope"] is None or regime["qqq_slope"] is None:
                _record_health("indices", "SPY / QQQ", "error",
                               "Continuous SPY and QQQ minute bars were not available; adaptive entries are paused.",
                               "Check the market data connection and retry the decision.")
            else:
                _record_health("indices", "SPY / QQQ", "ok",
                               "Continuous SPY and QQQ minute bars were verified through the decision time.")
        except Exception as exc:
            _record_health("indices", "SPY / QQQ", "error",
                           "SPY and QQQ minute bars could not be verified; adaptive entries are paused.",
                           "Check the market data connection and retry the decision.")
            try:
                core._ledger({"kind": "indices_unavailable", "day": day,
                              "why": str(exc) or type(exc).__name__,
                              "detail": getattr(exc, "detail", None)})
            except Exception:
                pass
    if regime["spy_slope"] is None or regime["qqq_slope"] is None:
        regime["reasons"].append("Opening SPY/QQQ VWAP data unavailable or incomplete")
    cards = cards or []
    # Candle rule: the regime reads the FIRST break of every card (board_direction), exactly the board it
    # read before the rule; a card without it was built with the rule off, where direction is the first break.
    # Flow rules 1/2 set board_direction the same way (the first old-gate break), so the board is unchanged.
    from . import flow
    _bd = (lambda c: c.get("board_direction") or c.get("direction")) \
        if (config.CANDLE_RULE or flow.entry_rules_on()) else (lambda c: c.get("direction"))
    shorts = sum(_bd(c) == "short" for c in cards)
    longs = sum(_bd(c) == "long" for c in cards)
    if not cards or shorts + longs != len(cards):
        regime["reasons"].append("No complete directional board")
    else:
        regime["short_frac"] = round(shorts / len(cards), 3)
        regime["breadth_ratio"] = round(longs / shorts, 2) if shorts else None
    if regime["reasons"]:
        return regime
    if not ADAPTIVE_CONFIG["MIN_BOARD_SHORT_FRAC"] <= shorts / len(cards) <= ADAPTIVE_CONFIG["MAX_BOARD_SHORT_FRAC"]:
        regime["classification"] = "ONE_SIDED"
        limit = ">75% limit" if shorts / len(cards) > 0.75 else "<25% limit"
        regime["reasons"].append(f"Board is {shorts / len(cards):.0%} short ({limit})")
    else:
        regime.update(classification="CALM_TREND", action="TRADE_NORMAL")
    return regime

