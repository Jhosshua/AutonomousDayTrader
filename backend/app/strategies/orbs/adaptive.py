RESULT_LINE = re.compile(
    r"\b(Q[1-4]|H[12]|FY\d{2,4})\b[^|]*?\b(?:Adj\.?|Adjusted|GAAP)?\s*(EPS|EPADS|EPADR)\s*\$?\(?-?[\d.]+\)?\s*(Beats?|Misses|Miss|Tops|In[- ]Line With)\b",
    re.I
)
GUIDANCE_LINE = re.compile(r"\b(Raises|Lowers|Cuts|Boosts|Guides|Sees)\b.*?\b(FY|Q[1-4]|Revenue|Sales|EPS)\b", re.I)
CONTRACT_LINE = re.compile(r"\b(?:FDA (?:Approves|Approval|Clearance)|(?:Awarded|Wins|Secures|Receives)\b[^.;]*\bContract)\b", re.I)
NEGATIVE_CONTRACT = re.compile(r"\b(?:not|denied|rejects?|rejected|withdraws?|withdrawn|terminates?|terminated|cancelled|cancels?|fails?)\b", re.I)
OFFERING_LINE = re.compile(r"\b(Public Offering|Secondary Offering|Form S-3|Priced Offering)\b", re.I)

def classify_catalyst(headline):
    """Classifies a news headline into the 5-Tier NLP Taxonomy:
    T1: Official Earnings Beat/Miss
    T2: Major Structural Contract / FDA Clearance
    T3: Dilutive Secondary Offering (toxic for longs)
    T4: Guidance Revision Alone
    T5: General / Analyst / Ordinary
    """
    if not headline:
        return {"tier": "T5", "type": "none", "grade": None, "score": 0.0}

    # Check T3: Secondary Offering (instant long veto)
    if OFFERING_LINE.search(headline):
        return {"tier": "T3", "type": "offering", "grade": "dilution", "score": -2.0}

    # Check T1: Canonical Results Line
    m = RESULT_LINE.search(headline)
    if m:
        w = m.group(3).lower()
        grade = "beat" if w.startswith(("beat", "top")) else "miss" if w.startswith("miss") else "inline"
        # Check guidance synergy
        guidance = "neutral"
        if GUIDANCE_LINE.search(headline):
            gm = GUIDANCE_LINE.search(headline).group(1).lower()
            if gm in ("raises", "boosts"): guidance = "raised"
            elif gm in ("lowers", "cuts"): guidance = "lowered"
        score = 2.0 if grade == "beat" else -2.0 if grade == "miss" else 0.5
        if guidance == "raised": score += 1.0
        elif guidance == "lowered": score -= 1.0
        return {"tier": "T1", "type": "earnings", "grade": grade, "guidance": guidance, "score": score}

    # Check T2: Contract / FDA Approval
    if CONTRACT_LINE.search(headline) and not NEGATIVE_CONTRACT.search(headline):
        return {"tier": "T2", "type": "contract_fda", "grade": "positive", "score": 1.5}

    # Check T4: Guidance Revision
    if GUIDANCE_LINE.search(headline):
        gm = GUIDANCE_LINE.search(headline).group(1).lower()
        grade = "raised" if gm in ("raises", "boosts") else "lowered" if gm in ("lowers", "cuts") else "neutral"
        score = 1.0 if grade == "raised" else -1.0 if grade == "lowered" else 0.0
        return {"tier": "T4", "type": "guidance", "grade": grade, "score": score}

    return {"tier": "T5", "type": "general", "grade": "neutral", "score": 0.0}

NEWS_PAGE_CAP = 40
# One news page may be retried this many times inside the fetch budget. 2026-10-02: nine ORB
# robots scan the shared relay at once and a single transport glitch on one page sat a bot out
# for the whole day. Transient failures retry; data defects and client errors still fail closed.
NEWS_PAGE_ATTEMPTS = 3
NEWS_RETRIABLE_HTTP = (429, 500, 502, 503, 504)
_news_sleep = _t.sleep


def _news_retry_after(exc, fallback):
    try:
        value = float((exc.headers or {}).get("Retry-After", ""))
        return min(value, 10.0) if value >= 0.0 else fallback
    except (TypeError, ValueError, AttributeError):
        return fallback


def _relay_page(req, deadline, per_try=10.0, what="news"):
    """One relay page (news, index bars), with bounded retries for transport and relay-busy
    failures. Each try waits at most ``per_try`` seconds and never past ``deadline``.

    Raises NewsDataError carrying ``detail`` (attempts, cause class and text) so the
    caller can record why a wave was sat out; health telemetry never carries raw text.
    """
    last = None
    attempts = 0
    for attempt in range(1, NEWS_PAGE_ATTEMPTS + 1):
        remaining = deadline - _t.monotonic()
        if remaining <= 0:
            break
        try:
            timeout = max(0.1, min(per_try, remaining))
            attempts += 1
            with core.urlopen(req, timeout=timeout) as resp:
                return json.load(resp)
        except urllib.error.HTTPError as exc:
            last = exc
            if exc.code not in NEWS_RETRIABLE_HTTP:
                break
            pause = _news_retry_after(exc, min(0.5 * (2 ** (attempt - 1)), 4.0))
        except Exception as exc:
            last = exc
            pause = min(0.5 * (2 ** (attempt - 1)), 4.0)
        if attempt >= NEWS_PAGE_ATTEMPTS or pause > max(0.0, deadline - _t.monotonic()):
            break
        _news_sleep(pause)
    if last is None:
        err = NewsDataError(f"{what} budget exhausted")
        err.detail = {"attempts": attempts, "cause": "no time left for a request"}
        raise err
    err = NewsDataError(f"{what} provider request failed")
    err.detail = {"attempts": attempts, "cause": f"{type(last).__name__}: {str(last)[:160]}"}
    raise err from last


def fetch_earnings_headlines(symbols, freeze_dt, budget_s=30.0):
    """Fetch complete, timestamped news data or fail closed.

    An empty result is valid only after every batch has reached its terminal page. A
    timeout, malformed response, or pagination cap means dilution is unknowable and
    raises ``NewsDataError`` so the caller can take an explicit cash pass.
    """
    symbols = sorted({str(s).upper() for s in symbols if s})
    if not symbols:
        _news_ok(0)
        return {}
    _record_health("news", "Company news", "waiting", "Checking complete company news coverage.")

    start_iso = (freeze_dt - timedelta(hours=49)).astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    end_iso = freeze_dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    url_base = config.NEWS_URL          # relay proxy; this bot holds no Alpaca credentials
    batches = [symbols[i:i + 40] for i in range(0, len(symbols), 40)]
    deadline = _t.monotonic() + max(0.1, float(budget_s))
    candidates = {}

    try:
        for batch in batches:
            page_token = None
            pages = 0
            while True:
                remaining = deadline - _t.monotonic()
                if remaining <= 0:
                    raise NewsDataError("news budget exhausted")
                if pages >= NEWS_PAGE_CAP:
                    raise NewsDataError("news pagination cap reached")
                q = {"symbols": ",".join(batch), "start": start_iso, "end": end_iso,
                     "limit": 50, "sort": "desc", "include_content": "false"}
                if page_token:
                    q["page_token"] = page_token
                req = urllib.request.Request(url_base + "?" + urllib.parse.urlencode(q),
                                             headers=dict(config.RELAY_HEADERS))
                data = _relay_page(req, deadline)
                if _t.monotonic() > deadline:
                    raise NewsDataError("news budget exhausted")
                if not isinstance(data, dict) or not isinstance(data.get("news"), list):
                    raise NewsDataError("news provider response malformed")
                pages += 1
                for item in data["news"]:
                    if not isinstance(item, dict):
                        raise NewsDataError("invalid news item")
                    headline = item.get("headline", "")
                    cat = classify_catalyst(headline)
                    if cat["grade"] not in ("beat", "miss", "positive", "dilution", "raised", "lowered"):
                        continue
                    syms = item.get("symbols") or []
                    if not isinstance(syms, list) or len(syms) > 3:
                        if not isinstance(syms, list): raise NewsDataError("invalid news symbols")
                        continue
                    raw_created = item.get("created_at")
                    try:
                        parsed = datetime.fromisoformat(str(raw_created).replace("Z", "+00:00"))
                        # A naive created_at has no market-time provenance. Do not let
                        # the host timezone silently turn it into an observation time.
                        if parsed.tzinfo is None or parsed.utcoffset() is None:
                            raise ValueError("missing timezone")
                        ts = parsed.astimezone(ET)
                    except (TypeError, ValueError, OverflowError):
                        raise NewsDataError("relevant news timestamp unavailable")
                    hrs = (freeze_dt - ts).total_seconds() / 3600.0
                    if not (0.0 <= hrs <= 48.0):
                        continue
                    row = {"hours_ago": round(hrs, 1), "result": cat["grade"],
                           "tier": cat["tier"], "catalyst": cat,
                           "report_datetime_ET": ts.strftime("%Y-%m-%d %H:%M"),
                           "headline": str(headline)[:140], "_ts": ts.timestamp()}
                    for symbol in syms:
                        symbol = str(symbol).upper()
                        if symbol in batch:
                            candidates.setdefault(symbol, []).append(row)
                page_token = data.get("next_page_token")
                if not page_token:
                    break
    except NewsDataError:
        _news_error()
        raise
    except Exception:
        _news_error()
        raise NewsDataError("news provider response unavailable")

    # A later offering must veto an earlier earnings beat for the same symbol. The
    # previous first-row-wins behavior made dilution disappear when it was not newest.
    priority = {"T3": 4, "T1": 3, "T2": 2, "T4": 1}
    found = {}
    for symbol, rows in candidates.items():
        chosen = max(rows, key=lambda row: (priority.get(row["tier"], 0), row["_ts"]))
        chosen = dict(chosen)
        chosen.pop("_ts", None)
        found[symbol] = chosen
    _news_ok(len(found))
    return found

# ---- Deal rule (DEAL_RULE_LIVE_PLAN_2026-10-01.md): a company-announced new deal blocks a new SHORT ----
DEAL_WIN = re.compile(r"\b(?:signs|signed|wins|won(?!['’]t)|secures|secured|awarded|lands|landed|selected|"
                      r"inks|inked|receives|received|gets|books|booked)\b", re.I)
DEAL_NOUN = re.compile(r"\b(?:deal|contract|order|agreement|award)\b", re.I)
DEAL_DOUBT = re.compile(r"\b(?:acquired|acquire|acquisition|merger|take private|taken private|to sell|sale of|divest|"
                        r"financing|credit|loan|notes|offering|settlement|lease|lawsuit|ruling|court|dispute|"
                        r"executive order|award for|price target|order book|loss|in talks|nears|considering|"
                        r"reportedly|rumou?r|stop-work|losing|lost|show cause|notice)\b", re.I)
DEAL_REPORT = re.compile(r"(?::\s*report\b|-\s*report\b|\breport:)", re.I)
DEAL_BUDGET_S = 8.0
_DEAL_BLOCKED = {}   # day -> {symbol: {"ts", "headline"}}; a block holds for the rest of the day


def is_deal_headline(headline):
    """True when the headline announces the company signing/winning a new deal, contract or order."""
    h = headline if isinstance(headline, str) else ""
    return bool(h and DEAL_WIN.search(h) and DEAL_NOUN.search(h) and not DEAL_DOUBT.search(h)
                and not NEGATIVE_CONTRACT.search(h) and not DEAL_REPORT.search(h))


def prior_close(freeze_dt):
    """Actual prior-session close from pre-open calendar evidence; no network calls.

    An unknown weekday must not be assumed to be a session: on the morning after
    a holiday that loses the whole weekend's news. Missing evidence uses the
    plan's explicit 96-hour fallback, with a separate deal-window warning.
    """
    from . import session_calendar
    close = session_calendar.prior_session_close(freeze_dt.astimezone(ET).date())
    if close is not None:
        _record_health("deal_window_fallback", "Deal news window", "ok",
                       "Deal news starts at the verified prior-session close.")
        return close
    _record_health("deal_window_fallback", "Deal news window", "warning",
                   "Prior-session close evidence is unavailable; deal news uses the 96-hour fallback.",
                   "Check the pre-open calendar and reference-data preparation.")
    return freeze_dt - timedelta(hours=96)


def fetch_deal_headlines(symbols, freeze_dt, budget_s=DEAL_BUDGET_S):
    """Return ({symbol: {"ts", "headline"}}, complete). Never raises: any failure returns what was
    found with complete=False, so a news glitch never sits the day out (fails open for this rule only)."""
    symbols = sorted({str(s).upper() for s in symbols if s})
    found = {}
    if not symbols:
        return found, True
    try:
        start_dt = prior_close(freeze_dt)
        start_iso = start_dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        end_iso = freeze_dt.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        deadline = _t.monotonic() + max(0.1, float(budget_s))
        for batch in [symbols[i:i + 40] for i in range(0, len(symbols), 40)]:
            page_token, pages = None, 0
            while True:
                remaining = deadline - _t.monotonic()
                if remaining <= 0 or pages >= NEWS_PAGE_CAP:
                    raise NewsDataError("deal news budget exhausted")
                q = {"symbols": ",".join(batch), "start": start_iso, "end": end_iso,
                     "limit": 50, "sort": "desc", "include_content": "false"}
                if page_token:
                    q["page_token"] = page_token
                req = urllib.request.Request(config.NEWS_URL + "?" + urllib.parse.urlencode(q),
                                             headers=dict(config.RELAY_HEADERS))
                with core.urlopen(req, timeout=max(0.1, min(5.0, remaining))) as resp:
                    data = json.load(resp)
                if not isinstance(data, dict) or not isinstance(data.get("news"), list):
                    raise NewsDataError("deal news response malformed")
                pages += 1
                for item in data["news"]:
                    try:
                        syms = item.get("symbols")
                        if not isinstance(syms, list) or len(syms) != 1:
                            continue
                        sym = str(syms[0]).upper()
                        if sym not in batch or not is_deal_headline(item.get("headline")):
                            continue
                        ts = datetime.fromisoformat(str(item.get("created_at")).replace("Z", "+00:00"))
                        if ts.tzinfo is None or ts.utcoffset() is None:
                            continue
                        ts = ts.astimezone(ET)
                        if not (start_dt <= ts <= freeze_dt):
                            continue
                        if sym not in found or ts > found[sym]["_ts"]:
                            found[sym] = {"ts": ts.strftime("%Y-%m-%d %H:%M"),
                                          "headline": item["headline"][:140], "_ts": ts}
                    except Exception:
                        continue          # one bad item never spoils the rest
                page_token = data.get("next_page_token")
                if not page_token:
                    break
        complete = True
    except Exception:
        complete = False
    for row in found.values():
        row.pop("_ts", None)
    if complete:
        _record_health("deal_news", "Deal news", "ok",
                       "Deal news checked for today's short candidates." if not found else
                       f"Deal news checked; {len(found)} short candidate(s) had a company deal announcement.")
    else:
        _record_health("deal_news", "Deal news", "warning",
                       "Deal news could not be read completely; shorts not already blocked trade as normal.",
                       "Check the relay news proxy.")
    return found, complete


def _sticky_deal_blocks(day):
    """Blocks already made today: this process's set plus today's skip_deal ledger rows (survives a restart)."""
    out = dict(_DEAL_BLOCKED.get(str(day), {}))
    try:
        if str(day) == core.today():
            for row in core._todays("skip_deal"):
                sym = str(row.get("symbol") or "").upper()
                if sym and sym not in out:
                    out[sym] = {"ts": row.get("news_ts", row.get("ts", "")), "headline": row.get("headline", "")}
    except Exception:
        pass
    return out

