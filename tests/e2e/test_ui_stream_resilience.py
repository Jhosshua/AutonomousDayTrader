# 1. High-Frequency State Message Updates (100 msgs/sec & Burst)
# ============================================================================

def test_high_frequency_broadcast_and_receipt(client):
    """
    Empirically verify high-frequency state updates (100 msgs roundtrip burst) across WebSocket.
    Ensures connection remains open, frames are received, and state payload schema passes.
    """
    # Setup test bracket & position for AAPL
    account.positions["AAPL"] = Position("AAPL", PositionSide.LONG, 100, 150.0, 152.0)
    bracket_manager.create_bracket("brk_hf_test", "AAPL", "LONG", 100, 150.0, 148.0)

    try:
        with client.websocket_connect("/ws/ui") as ws:
            # Initial state broadcast upon connection
            initial_raw = ws.receive_text()
            initial_data = json.loads(initial_raw)
            assert initial_data["type"] == "STATE_UPDATE"
            assert validate_ui_state_payload(initial_data) is True

            # Send a rapid burst of 100 state updates by modulating stop levels
            t0 = time.monotonic()
            for i in range(1, 101):
                new_stop = round(148.0 + (i * 0.01), 2)
                ws.send_text(json.dumps({
                    "action": "TIGHTEN_STOP",
                    "symbol": "AAPL",
                    "new_stop": new_stop,
                }))
                msg_raw = ws.receive_text()
                data = json.loads(msg_raw)
                assert data["type"] == "STATE_UPDATE"
                assert validate_ui_state_payload(data) is True
                assert data["primary_position"]["stop_loss"] == new_stop

            duration = time.monotonic() - t0
            # 100 round-trip broadcasts and receipts should execute cleanly in < 1.0 second
            assert duration < 1.0
            throughput = 100.0 / duration
            assert throughput >= 100.0
    finally:
        bracket_manager.symbol_to_bracket.pop("AAPL", None)
        account.positions.pop("AAPL", None)


# ============================================================================
# 2. Malformed JSON Frame Handling (Graceful Logging, Zero Crash)
# ============================================================================

def test_malformed_json_frames_handled_gracefully(client):
    """
    Verify backend WebSocket handler survives adversarial / malformed payloads:
    - Truncated JSON
    - Non-JSON strings
    - JSON primitives (null, number, boolean)
    - Empty strings
    - Corrupted structures
    Ensures socket is NOT abruptly severed and continues accepting valid messages.
    """
    with client.websocket_connect("/ws/ui") as ws:
        # Discard initial snapshot
        _ = ws.receive_text()

        malformed_inputs = [
            '{"action": "FLATTEN_POSITION", "sym',  # Truncated syntax
            'NOT_A_VALID_JSON_STRING',
            '',                                      # Empty frame
            'null',
            '12345',
            'true',
            '[]',
            '{"unknown_field": 42}',
            '{"action": null}',
            '{"action": "UNKNOWN_ACTION_OPCODE"}',
        ]

        for payload in malformed_inputs:
            # Should not raise WebSocketDisconnect or unhandled backend exception
            ws.send_text(payload)

        # Immediate self-healing / liveness check: send a valid action
        ws.send_text(json.dumps({"action": "FLATTEN_ALL"}))

        # Connection is still alive and responsive: receive reply
        reply = ws.receive_text()
        data = json.loads(reply)
        assert data["type"] == "STATE_UPDATE"
        assert validate_ui_state_payload(data) is True


