def test_action_serialization_flatten_position(client):
    """
    Verify payload generated by frontend `flattenPosition("NVDA")`:
    `{"action": "FLATTEN_POSITION", "symbol": "NVDA"}`
    matches backend schema and executes correctly.
    """
    # Seed account with a real Position instance
    account.positions["NVDA"] = Position("NVDA", PositionSide.LONG, 100, 125.0, 126.0)

    try:
        with client.websocket_connect("/ws/ui") as ws:
            _ = ws.receive_text()

            # Dispatch frontend serialized payload
            frontend_payload = {"action": "FLATTEN_POSITION", "symbol": "NVDA"}
            ws.send_text(json.dumps(frontend_payload))

            # Backend triggers manual_flatten and broadcasts state
            update_raw = ws.receive_text()
            update = json.loads(update_raw)
            assert update["type"] == "STATE_UPDATE"
            assert "NVDA" not in [p.get("symbol") for p in update.get("all_positions", [])]
    finally:
        account.positions.pop("NVDA", None)


